#!/usr/bin/env python3
"""Import Rack Studio's public catalog and selected reusable visual assets.

This is an optional maintainer tool. The app needs neither this tool nor the
source checkout at runtime: all generated data is inlined in portable HTML.
Only catalog.js and the named public asset files are read. Rack Studio's layout,
network inventory, local notes, and other user data are never imported.
"""
from __future__ import annotations

import argparse
import base64
import json
import mimetypes
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
PANELS = (
    "dell-poweredge-r750",
    "hpe-proliant-dl360-gen10",
    "cisco-c9300-48p",
    "arista-dcs-7010t-48",
    "synology-rs3614xs-plus",
    "apc-smt1500rmi2uc",
    "supermicro-sys-6029tp-chassis",
    "generic-24-port-copper-patch-panel",
    "generic-lc-24-port-fiber-patch-panel",
)
STENCILS = (
    "server", "server-network", "switch", "wall-fire",
    "desktop-tower-monitor", "nas", "router-network", "lan", "wan",
    "cloud-outline", "database-outline", "web", "web-box", "wifi",
    "access-point-network", "ethernet", "ethernet-cable",
    "shield-lock-outline", "cellphone-link", "cctv",
)


def svg_body(path: Path) -> str:
    """Accept only the upstream MDI path data, excluding executable SVG."""
    root = ET.fromstring(path.read_bytes())
    if root.attrib.get("viewBox") != "0 0 24 24":
        raise ValueError(f"Unexpected stencil dimensions: {path.name}")
    paths = []
    for child in root:
        if child.tag.rsplit("}", 1)[-1] != "path":
            raise ValueError(f"Unexpected SVG element: {path.name}")
        data = child.attrib.get("d", "")
        if not re.fullmatch(r"[MmZzLlHhVvCcSsQqTtAaEe0-9.,+\s-]+", data):
            raise ValueError(f"Unexpected path content: {path.name}")
        paths.append(f'<path fill="currentColor" d="{data}"/>')
    return "".join(paths)


def build(source: Path, output: Path) -> dict:
    content = (source / "catalog.js").read_text(encoding="utf-8")
    match = re.fullmatch(r"\s*/\*.*?\*/\s*window\.RACK_LIBRARY\s*=\s*(\{.*\});?\s*", content, re.S)
    if not match:
        raise ValueError("Expected a generated Rack Studio catalog literal")
    library = json.loads(match.group(1))
    for key, item in library.items():
        image = item.pop("img", None)
        if image:
            item["imageSource"] = image
        if key in PANELS:
            if not image:
                raise ValueError(f"Selected panel is missing: {key}")
            file = (source / image).resolve()
            if not file.is_relative_to((source / "elevation-images").resolve()):
                raise ValueError("Panel outside the public elevation-image tree")
            mime = mimetypes.guess_type(file.name)[0]
            if mime not in {"image/png", "image/jpeg", "image/webp", "image/gif"}:
                raise ValueError(f"Unexpected panel format: {key}")
            item["img"] = "data:" + mime + ";base64," + base64.b64encode(file.read_bytes()).decode("ascii")
    icons = {name: svg_body(source / "network-assets" / (name + ".svg")) for name in STENCILS}
    info = {
        "source": "NetBox Community devicetype-library via Rack Studio",
        "sourceRevision": "32ad450f1ca35a1e7a09b172c9817ba164f72597",
        "license": "CC0-1.0", "modelCount": len(library),
        "embeddedPanels": list(PANELS), "stencilCount": len(icons),
        "stencilLicense": "Apache-2.0 (Pictogrammers Free License)",
    }
    js = "/* Generated by tools/build_rack_catalog.py; public library assets only.\n"
    js += " * Catalog/front panels: CC0-1.0. MDI stencils: Apache-2.0.\n"
    js += " * See THIRD_PARTY_NOTICES.md for source, attribution, and license text. */\n"
    for name, value in (("RACK_LIBRARY", library), ("RACK_STENCILS", icons), ("RACK_LIBRARY_INFO", info)):
        js += "globalThis." + name + "=" + json.dumps(value, separators=(",", ":"), ensure_ascii=True).replace("</", "<\\/") + ";\n"
    output.write_text(js, encoding="utf-8")
    return info


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rack-studio", type=Path, required=True, help="Path to the existing Rack Studio checkout")
    parser.add_argument("--output", type=Path, default=ROOT / "src" / "rack-catalog.js")
    args = parser.parse_args()
    print(json.dumps(build(args.rack_studio, args.output), indent=2))
